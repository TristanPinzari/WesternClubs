import { sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import {
  ATTENDANCE_PURPOSES,
  CLUB_ROLES,
  EVENT_CATEGORIES,
  RSVP_STATUSES,
  type Links,
} from "@orbit/shared";
import { user } from "./auth-schema";

// Drizzle docs: https://orm.drizzle.team/docs/sql-schema-declaration
