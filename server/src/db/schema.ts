// profile: defined below the event table (its `interests` column uses the event_category enum).

// event: posted by a club
export const eventCategory = pgEnum("event_category", EVENT_CATEGORIES);

export const event = pgTable(
  "event",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    clubId: uuid("club_id")
      .notNull()
      .references(() => club.id, { onDelete: "cascade" }), // delete club -> delete its events
    // Optional: if the exec who posted it deletes their account, keep the event.
    createdById: text("created_by_id").references(() => user.id, {
      onDelete: "set null",
    }),
    title: text("title").notNull(),
    description: text("description").notNull().default(""),
    category: eventCategory("category").notNull(),
    startsAt: ts("starts_at").notNull(),
    endsAt: ts("ends_at"),
    location: text("location").notNull().default(""),
    priceCents: integer("price_cents").notNull().default(0), // money as cents, never floats
    eligibility: text("eligibility").notNull().default(""),
    registrationUrl: text("registration_url"),
    imageKey: text("image_key"), // S3 key, like club.logoKey
    cancelledAt: ts("cancelled_at"), // null = not cancelled
    createdAt: ts("created_at").notNull().defaultNow(),
    updatedAt: ts("updated_at").notNull().defaultNow(),
  },
  (t) => [
    // We filter and sort by these on almost every request, so index them.
    index("event_starts_at_idx").on(t.startsAt),
    index("event_club_id_idx").on(t.clubId),
  ],
);

// profile: extra student info, one row per user. A user without a row is treated as a
// public profile with empty fields (most users won't fill it in straight away).
// Profile picture: NOT stored here. It's Better Auth's `user.image` column, holding the
// FULL public image URL (not an S3 key like club.logoKey), because Better Auth returns
// user.image directly in the session (useSession()).
export const profile = pgTable("profile", {
  userId: text("user_id")
    .primaryKey()
    .references(() => user.id, { onDelete: "cascade" }),
  program: text("program"),
  yearOfStudy: integer("year_of_study"),
  bio: text("bio"),
  // An array of the event_category enum, not free text, so the "For you" feed can match
  // interests to event categories. The database itself rejects anything else.
  interests: eventCategory("interests")
    .array()
    .notNull()
    .default(sql`'{}'`),
  links: jsonb("links").$type<Links>().notNull().default({}),
  // Controls profile visibility, whether others can follow you, and whether you can
  // appear on attendee lists.
  isPublic: boolean("is_public").notNull().default(true),
  createdAt: ts("created_at").notNull().defaultNow(),
  updatedAt: ts("updated_at").notNull().defaultNow(),
});

// event_rsvp: a user's "Interested" / "Going" on an event
export const rsvpStatus = pgEnum("rsvp_status", RSVP_STATUSES);
export const attendancePurpose = pgEnum(
  "attendance_purpose",
  ATTENDANCE_PURPOSES,
);

export const eventRsvp = pgTable(
  "event_rsvp",
  {
    eventId: uuid("event_id")
      .notNull()
      .references(() => event.id, { onDelete: "cascade" }), // delete event -> delete its RSVPs
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }), // delete account -> delete their RSVPs
    status: rsvpStatus("status").notNull(),
    // Visible by default. false = RSVP'd anonymously: counted, but never named.
    showOnAttendeeList: boolean("show_on_attendee_list")
      .notNull()
      .default(true),
    purpose: attendancePurpose("purpose"), // optional: why you're going
    lookingForBuddy: boolean("looking_for_buddy").notNull().default(false),
    createdAt: ts("created_at").notNull().defaultNow(),
    updatedAt: ts("updated_at").notNull().defaultNow(),
  },
  (t) => [
    // One RSVP per user per event. Changing "Interested" to "Going" updates this row
    // instead of adding a second one, so nobody is counted twice.
    primaryKey({ columns: [t.eventId, t.userId] }),
    // The PK already makes "RSVPs for this event" fast. This makes "my RSVPs"
    // (the dashboard) fast too.
    index("event_rsvp_user_id_idx").on(t.userId),
  ],
);

