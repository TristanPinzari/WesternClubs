// Better Auth's tables (user, session, account, verification) live in auth-schema.ts.
// That file is generated by Better Auth's CLI, so don't edit it by hand.
// Better Auth user ids are TEXT, not uuid, so every foreign key to user is text.
export * from "./auth-schema";

const ts = (name: string) => timestamp(name, { withTimezone: true });

// =============================================================================
// EXAMPLE 1: a basic table (uuid primary key, required + optional columns)
// =============================================================================

export const club = pgTable("club", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: text("name").notNull(),
  slug: text("slug").notNull().unique(), // URL-friendly name, e.g. "western-ai"
  description: text("description").notNull().default(""),
  logoKey: text("logo_key"), // S3 object key, not a full URL; nullable = optional
  links: jsonb("links").$type<Links>().notNull().default({}), // { instagram: "https://..." }
  createdAt: ts("created_at").notNull().defaultNow(),
  updatedAt: ts("updated_at").notNull().defaultNow(),
});

// =============================================================================
// EXAMPLE 2: an enum + a join table with foreign keys and a composite primary key
// =============================================================================

export const clubRole = pgEnum("club_role", CLUB_ROLES);

export const clubMember = pgTable(
  "club_member",
  {
    clubId: uuid("club_id")
      .notNull()
      .references(() => club.id, { onDelete: "cascade" }), // delete club -> delete memberships
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    role: clubRole("role").notNull(),
    createdAt: ts("created_at").notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.clubId, t.userId] }), // a user can only be in a club once
    // At most one owner per club. A *partial* unique index: club_id must be unique,
    // but only among rows WHERE role = 'owner'. So many admins/editors are fine, and the
    // database refuses a second owner even if an endpoint has a bug.
    uniqueIndex("club_member_one_owner")
      .on(t.clubId)
      .where(sql`${t.role} = 'owner'`),
  ],
);

